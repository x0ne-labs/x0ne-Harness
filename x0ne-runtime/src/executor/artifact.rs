    ///
    /// A failure here means the runtime accepted a model-chosen loader for a
    /// long-lived, detached process.
    #[test]
    fn artifact_serve_refuses_an_env_that_chooses_the_program() {
        for key in ["PATH", "LD_PRELOAD", "BASH_ENV", "PYTHONPATH"] {
            let r = serve(&[(key, "/tmp/evil")]);
            assert!(!r.success, "ArtifactServe accepted {key}");
            let text = serde_json::to_string(&r).expect("serialise");
            assert!(
                text.contains("env_var_denied") && text.contains(key),
                "the refusal must name the key and say it is an env refusal: {text}"
            );
        }
    }

    /// SECURITY: the shape of the command line is judged BEFORE the registry is
    /// consulted, so a hostile line is refused whether or not the id exists.
    ///
    /// The id here is deliberately unknown. If the check moved below the
    /// registry lookup, this would come back as "unknown artifact" and the
    /// refusal would depend on an unrelated fact — the difference between a
    /// gate and a coincidence.
    ///
    /// A failure here means `sh -c` is back, or is one valid id away.
    #[test]
    fn a_serve_command_is_refused_on_its_shape_before_the_registry_is_read() {
        for line in [
            "python3 --version ; cat /etc/passwd",
            "python3 -m http.server $(id -un)",
            "python3 > /tmp/leak",
            "",
        ] {
            let action = Action::ArtifactServe {
                id: "no-such-artifact".into(),
                command: line.into(),
                port: None,
                env: HashMap::new(),
            };
            let r = tokio::runtime::Builder::new_current_thread()
                .enable_all()
                .build()
                .expect("runtime")
                .block_on(artifact_serve(&action, &AppConfig::defaults()));
            assert!(!r.success, "a shell line was accepted: {line:?}");
            let text = serde_json::to_string(&r).expect("serialise");
            assert!(
                !text.contains("unknown artifact"),
                "the shape check runs after the registry lookup, so the refusal \
                 depends on the id: {text}"
            );
        }
    }

    /// SECURITY: `session_id` is joined into the artifact storage path. One
    /// component, no separators, no climbing.
    ///
    /// Measured 2026-08-15: `session_id: "../../../../../../tmp/x0ne-traversal"`
    /// created a real directory outside `…/artifacts/`, and `ArtifactServe`
    /// makes the artifact root its child's working directory.
    ///
    /// A failure here means an artifact can be planted anywhere the runtime can
    /// write, and then served from there.
    #[test]
    fn a_session_id_cannot_climb_out_of_the_artifact_store() {
        for hostile in [
            "../../../../../../tmp/x0ne-traversal",
            "..",
            ".",
            "a/b",
            "a\\b",
            "",
        ] {
            assert!(
                check_session_id(hostile).is_err(),
                "session_id {hostile:?} was accepted"
            );
        }
        // The shape a session id actually has.
        assert!(check_session_id("sess_9f2a1c").is_ok());
        assert!(check_session_id("2026-08-15T20.47.32Z").is_ok());
    }

    /// The complement: an ordinary application variable is not what this filter
    /// is for, and a service that cannot be configured is a filter that gets
    /// reverted. The unknown id is what stops it here, one step further on.
    #[test]
    fn artifact_serve_still_accepts_ordinary_variables() {
        let r = serve(&[("DATABASE_URL", "postgres://localhost/x")]);
        let text = serde_json::to_string(&r).expect("serialise");
        assert!(
            !text.contains("env_var_denied"),
            "an ordinary variable was refused by the env filter: {text}"
        );
    }
