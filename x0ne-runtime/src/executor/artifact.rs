//! Executor for the `Artifact*` action family.
//!
//! Reads/writes the on-disk artifact registry (`crate::artifact`), supervises
//! service processes, and ensures the `x0ne-artifact-proxy` daemon is running.

use std::collections::HashMap;
use std::process::{Command, Stdio};

use chrono::Utc;

use crate::action::Action;
use crate::artifact::{
    self, allocate_service_port, new_artifact_id, pid_alive, terminate_pid, with_registry,
    Artifact, ArtifactKind, ArtifactRegistry, ArtifactState, ServiceSpec, DEFAULT_PROXY_PORT,
};
use crate::config::AppConfig;
use crate::result::{ActionOutput, ActionResult, ArtifactSummary, ErrorKind};

// ── Helpers ──────────────────────────────────────────────────────────────────

fn parse_kind(s: &str) -> Result<ArtifactKind, String> {
    match s.to_ascii_lowercase().as_str() {
        "static" | "" => Ok(ArtifactKind::Static),
        "service" | "dynamic" => Ok(ArtifactKind::Service),
        other => Err(format!(
            "unknown artifact kind '{}': use 'static' or 'service'",
            other
        )),
    }
}

fn kind_str(k: ArtifactKind) -> &'static str {
    match k {
        ArtifactKind::Static => "static",
        ArtifactKind::Service => "service",
    }
}

fn state_str(s: ArtifactState) -> &'static str {
    match s {
        ArtifactState::Created => "created",
        ArtifactState::Running => "running",
        ArtifactState::Stopped => "stopped",
        ArtifactState::Failed => "failed",
    }
}

/// A session id must name exactly one directory under the ephemeral store.
///
/// SECURITY: the value is joined into a filesystem path. Anything that can
/// introduce a component boundary (`/`, `\`), climb (`.`, `..`) or terminate a
/// C string (NUL) is refused. Empty is refused too: `join("")` silently yields
/// the parent, which would pool every session's artifacts in one directory.
fn check_session_id(sid: &str) -> Result<(), String> {
    if sid.is_empty() {
        return Err("session_id must not be empty".into());
    }
    if sid == "." || sid == ".." {
        return Err(format!(
            "session_id '{}' names a directory outside the artifact store",
            sid
        ));
    }
    for bad in ['/', '\\', '\0'] {
        if sid.contains(bad) {
            return Err(format!(
                "session_id must be a single path component: '{}' contains {:?}",
                sid, bad
            ));
        }
    }
    Ok(())
}

fn err(action: &str, kind: ErrorKind, msg: impl Into<String>) -> ActionResult {
    ActionResult::err(action, kind, msg, 0)
}

fn make_info(cv: &Artifact, proxy_port: u16) -> ActionOutput {
    ActionOutput::ArtifactInfo {
        id: cv.id.clone(),
        name: cv.name.clone(),
        artifact_kind: kind_str(cv.kind).into(),
        state: state_str(cv.state).into(),
        persistent: cv.persistent,
        url: cv.url(proxy_port),
        root_path: cv.root_path.to_string_lossy().into(),
        proxy_port,
        size_bytes: cv.size_bytes(),
        service_pid: cv.service.as_ref().and_then(|s| s.pid),
        service_port: cv.service.as_ref().map(|s| s.port),
    }
}

fn make_summary(cv: &Artifact, proxy_port: u16) -> ArtifactSummary {
    let age_secs = (Utc::now() - cv.created_at).num_seconds();
    ArtifactSummary {
        id: cv.id.clone(),
        name: cv.name.clone(),
        artifact_kind: kind_str(cv.kind).into(),
        state: state_str(cv.state).into(),
        persistent: cv.persistent,
        url: cv.url(proxy_port),
        root_path: cv.root_path.to_string_lossy().into(),
        size_bytes: cv.size_bytes(),
        age_secs,
        service_pid: cv.service.as_ref().and_then(|s| s.pid),
        service_port: cv.service.as_ref().map(|s| s.port),
    }
}

/// Effective proxy port (env override > registry value > default).
fn current_proxy_port(reg: &ArtifactRegistry) -> u16 {
    if let Ok(s) = std::env::var("X0NE_ARTIFACT_PROXY_PORT") {
        if let Ok(p) = s.parse() {
            return p;
        }
    }
    reg.proxy_port.unwrap_or(DEFAULT_PROXY_PORT)
}

/// Best-effort: probe the proxy's `/_health` endpoint (honours
/// `X0NE_ARTIFACT_PROXY_CHECK_HOST`).
fn proxy_running(port: u16) -> bool {
    artifact::proxy_health_probe(port)
}

/// No-op kept for the call-sites in `artifact_create` / `artifact_list` /
/// `artifact_serve` until they're rewritten. The standalone
/// `x0ne-artifact-proxy` binary is gone — serving now lives:
///
///  * inside the runtime itself (`crate::artifact_serve` axum app), so a
///    runtime in a sandbox serves its own files from inside the sandbox
///    (no host bind mount, no agent-generated bytes touching the host disk);
///  * inside the orchestrator (`artifact_router`), which listens on the
///    user-facing `127.0.0.1:7800` and reverse-proxies by artifact ID to
///    the runtime that owns it (host loopback in host mode, container IP
///    in sandbox mode).
fn ensure_proxy_running(_port: u16) {}

/// Detach the spawned service from the runtime's controlling terminal so
/// the process group survives our exit. We avoid pulling the `libc` crate
/// just for this one syscall.
#[inline]
fn libc_setsid() {
    extern "C" {
        fn setsid() -> i32;
    }
    // SAFETY: setsid(2) takes no argument and touches no memory of ours;
    // it is async-signal-safe, which the pre_exec caller below needs.
    unsafe {
        setsid();
    }
}

// ── ArtifactCreate ─────────────────────────────────────────────────────────────

pub async fn artifact_create(action: &Action, _cfg: &AppConfig) -> ActionResult {
    let Action::ArtifactCreate {
        name,
        kind,
        persistent,
        session_id,
    } = action
    else {
        return err(
            "ArtifactCreate",
            ErrorKind::Internal,
            "wrong action variant",
        );
    };

    let kind = match parse_kind(kind.as_deref().unwrap_or("static")) {
        Ok(k) => k,
        Err(m) => return err("ArtifactCreate", ErrorKind::InvalidInput, m),
    };
    let persistent = persistent.unwrap_or(false);
    let session_id = session_id
        .clone()
        .or_else(|| std::env::var("X0NE_SESSION_ID").ok());
    // SECURITY: `session_id` is model-supplied and is joined straight into the
    // storage path (`x0ne_artifact::ephemeral_dir`). Unvalidated, it walked out
    // of the store: `session_id: "../../../../../../tmp/x0ne-traversal"`
    // created `…/artifacts/ephemeral/../../…/tmp/x0ne-traversal/<id>/` and
    // `ArtifactServe` would then have run its child there (measured
    // 2026-08-15). One path component, no separators — that is the whole
    // contract this field ever had.
    if let Some(sid) = session_id.as_deref() {
        if let Err(why) = check_session_id(sid) {
            return err("ArtifactCreate", ErrorKind::InvalidInput, why);
        }
    }

    let id = new_artifact_id();
    let root = artifact::artifact_path(&id, persistent, session_id.as_deref());
    if let Err(e) = std::fs::create_dir_all(&root) {
        return err(
            "ArtifactCreate",
            ErrorKind::ExecutionFailed,
            format!("create_dir_all({}): {}", root.display(), e),
        );
    }

    let now = Utc::now();
    let artifact = Artifact {
        id: id.clone(),
        name: name.clone(),
        kind,
        state: ArtifactState::Created,
        persistent,
        root_path: root,
        session_id,
        created_at: now,
        updated_at: now,
        service: None,
    };

    let proxy_port = match with_registry(|reg| {
        let port = current_proxy_port(reg);
        if reg.proxy_port.is_none() {
            reg.proxy_port = Some(port);
        }
        reg.artifacts.insert(id.clone(), artifact.clone());
        port
    }) {
        Ok(p) => p,
        Err(e) => {
            return err(
                "ArtifactCreate",
                ErrorKind::ExecutionFailed,
                format!("registry: {}", e),
            )
        }
    };

    ensure_proxy_running(proxy_port);
    ActionResult::ok("ArtifactCreate", make_info(&artifact, proxy_port), 0)
}

// ── ArtifactList ───────────────────────────────────────────────────────────────

pub async fn artifact_list(_action: &Action, _cfg: &AppConfig) -> ActionResult {
    let reg = match artifact::load_registry() {
        Ok(r) => r,
        Err(e) => {
            return err(
                "ArtifactList",
                ErrorKind::ExecutionFailed,
                format!("registry: {}", e),
            )
        }
    };
    let port = current_proxy_port(&reg);
    // Same as ArtifactCreate: try to bring the proxy up so `/artifact` and the
    // first agent turn see `proxy_running: true` when the binary exists.
    ensure_proxy_running(port);
    let summaries: Vec<ArtifactSummary> = reg
        .list_sorted()
        .into_iter()
        .map(|c| make_summary(c, port))
        .collect();
    ActionResult::ok(
        "ArtifactList",
        ActionOutput::ArtifactListing {
            proxy_port: port,
            proxy_running: proxy_running(port),
            artifacts: summaries,
        },
        0,
    )
}

// ── ArtifactServe ──────────────────────────────────────────────────────────────

pub async fn artifact_serve(action: &Action, cfg: &AppConfig) -> ActionResult {
    let Action::ArtifactServe {
        id,
        command,
        port,
        env,
    } = action
    else {
        return err("ArtifactServe", ErrorKind::Internal, "wrong action variant");
    };
    // SECURITY: `command` is an argv, not a shell line. Refused here, before
    // the registry is touched, so the refusal does not depend on the id being
    // valid — and so a test can reach it. The port is not allocated yet; the
    // placeholder is safe because a port only ever contributes decimal digits
    // and cannot change the verdict (`serve_command::parse`, and its test
    // `the_allocated_port_cannot_change_the_verdict`). The real argv is parsed
    // again below, from the same function, with the allocated port.
    if let Err(refused) = x0ne_actions::serve_command::parse(command, 0) {
        return err("ArtifactServe", ErrorKind::InvalidInput, refused.message());
    }
    // SECURITY: same filter as RunCommand, and this site needs it more, not
    // less. The child is detached with `setsid`, so it outlives the action: a
    // PATH or LD_PRELOAD planted here keeps choosing programs long after the
    // turn that set it. Checked before the registry is touched, so the refusal
    // does not depend on the id being valid — and so a test can reach it. See
    // `x0ne_actions::env_keys`.
    if let Err(why) = crate::child_env::check_caller_env(env) {
        return err("ArtifactServe", ErrorKind::EnvVarDenied, why);
    }
    // Snapshot needed metadata under the registry lock.
    let snapshot = match with_registry(|reg| {
        let proxy_port = current_proxy_port(reg);
        let cv = match reg.artifacts.get(id) {
            Some(c) => c.clone(),
            None => return Err(format!("unknown artifact '{}'", id)),
        };
        if cv.kind != ArtifactKind::Service {
            return Err(format!(
                "artifact '{}' is kind=static; recreate with kind=service to attach a process",
                id
            ));
        }
        // Stop old PID if alive (re-serve replaces).
        if let Some(s) = &cv.service {
            if let Some(pid) = s.pid {
                if pid_alive(pid) {
                    terminate_pid(pid, 800);
                }
            }
        }
        let allocated = match port {
            Some(p) => *p,
            None => match allocate_service_port(reg) {
                Some(p) => p,
                None => return Err("no free service port available".into()),
            },
        };
        Ok((cv, proxy_port, allocated))
    }) {
        Ok(Ok(s)) => s,
        Ok(Err(m)) => return err("ArtifactServe", ErrorKind::InvalidInput, m),
        Err(e) => {
            return err(
                "ArtifactServe",
                ErrorKind::ExecutionFailed,
                format!("registry: {}", e),
            )
        }
    };
    let (cv, proxy_port, port_alloc) = snapshot;

    // Compose env: PORT=… is auto-set, plus user env. The keys were filtered at
    // the top of this function, before the registry was touched.
    let mut full_env: HashMap<String, String> = env.clone();
    full_env.insert("PORT".into(), port_alloc.to_string());
    full_env.insert("ARTIFACT_ID".into(), id.clone());
    full_env.insert(
        "ARTIFACT_ROOT".into(),
        cv.root_path.to_string_lossy().into(),
    );

    // SECURITY: the ONE tokenisation, shared with the policy gate
    // (`policy::commands_of`). `$PORT` is substituted here — the runtime, not a
    // shell, is what ever expanded it.
    let argv = match x0ne_actions::serve_command::parse(command, port_alloc) {
        Ok(a) => a,
        // Unreachable: the same call was made above with the placeholder port,
        // and the port cannot change the verdict. Kept as a refusal rather than
        // an `expect` so that a future change to `parse` fails closed.
        Err(refused) => return err("ArtifactServe", ErrorKind::InvalidInput, refused.message()),
    };
    let resolved_cmd = argv.join(" ");

    // SECURITY: the child's working directory is read from the registry, and
    // the registry is written by `ArtifactCreate` from a model-supplied
    // `session_id`. That field was joined into the storage path unvalidated, so
    // `session_id: "../../../../../../tmp/x0ne-traversal"` produced an artifact
    // root outside the store, and this spawn would have served it (measured
    // 2026-08-15). `ArtifactCreate` now refuses such a session id; this is the
    // enforcement point, re-resolving what it is about to use rather than
    // trusting what an earlier action recorded.
    let store_root = match std::fs::canonicalize(artifact::root_dir()) {
        Ok(r) => r,
        Err(e) => {
            return err(
                "ArtifactServe",
                ErrorKind::ExecutionFailed,
                format!("artifact store unreadable: {}", e),
            )
        }
    };
    let serve_root = match std::fs::canonicalize(&cv.root_path) {
        Ok(r) => r,
        Err(e) => {
            return err(
                "ArtifactServe",
                ErrorKind::ExecutionFailed,
                format!("artifact root unresolvable: {}", e),
            )
        }
    };
    if !crate::executor::confine::is_within_roots(&serve_root, std::slice::from_ref(&store_root)) {
        return err(
            "ArtifactServe",
            ErrorKind::PolicyDenied,
            format!(
                "artifact root '{}' is outside the artifact store '{}'",
                serve_root.display(),
                store_root.display()
            ),
        );
    }

    let log_path = serve_root.join(".artifact.log");
    let log_file = match std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(&log_path)
    {
        Ok(f) => f,
        Err(e) => {
            return err(
                "ArtifactServe",
                ErrorKind::ExecutionFailed,
                format!("open log: {}", e),
            )
        }
    };
    let log_clone = match log_file.try_clone() {
        Ok(f) => f,
        Err(e) => {
            return err(
                "ArtifactServe",
                ErrorKind::ExecutionFailed,
                format!("dup log: {}", e),
            )
        }
    };

    // SECURITY: `Command::new(program).args(rest)` — no shell, exactly as
    // `RunCommand` (`executor/process.rs`). This spawn used to be
    // `Command::new("sh").arg("-c").arg(line)`, the only shell in the runtime
    // and the one that falsified invariant 6 of docs/invariants.md. `;`, `|`, `>` and
    // `$(…)` are now argv bytes or, more usually, a refusal upstream.
    //
    // SECURITY: confined by bwrap. The artifact directory is writable
    // and the network is shared: the host proxy must reach the service port.
    let spawn = match crate::executor::isolation::plan(
        &cfg.isolation,
        &cfg.policy,
        &cfg.desktop,
        &argv[0],
        &argv[1..],
        serve_root.to_str(),
        &crate::executor::isolation::Options {
            extra_write: Some(&serve_root),
            share_network: true,
            ..Default::default()
        },
    ) {
        Ok(s) => s,
        Err(e) if e.kind() == crate::executor::isolation::UNAVAILABLE_KIND => {
            return err("ArtifactServe", ErrorKind::MissingDependency, e.to_string())
        }
        Err(e) => {
            return err(
                "ArtifactServe",
                ErrorKind::ExecutionFailed,
                format!("spawn '{}' failed: {}", resolved_cmd, e),
            )
        }
    };
    let mut child = Command::new(&spawn.program);
    // SECURITY: cleared environment before `full_env` is applied, never after.
    // This child is long-lived and detached (`setsid` below), so anything
    // inherited here outlives the action that started it. `full_env` — the
    // action's own map plus PORT/ARTIFACT_ID/ARTIFACT_ROOT — is applied on the
    // next line and survives, because `harden` runs first. See
    // `crate::child_env`.
    crate::child_env::harden(&mut child);
    child
        .args(&spawn.args)
        .current_dir(&serve_root)
        .envs(&full_env)
        .stdin(Stdio::null())
        .stdout(Stdio::from(log_file))
        .stderr(Stdio::from(log_clone));
    // SAFETY: between fork and exec the closure only calls setsid(2), which
    // is async-signal-safe, and allocates nothing, as pre_exec requires.
    unsafe {
        use std::os::unix::process::CommandExt;
        child.pre_exec(|| {
            libc_setsid();
            Ok(())
        });
    }
    let pid = match child.spawn() {
        Ok(c) => c.id(),
        Err(e) => {
            return err(
                "ArtifactServe",
                ErrorKind::ExecutionFailed,
                format!("spawn '{}' failed: {}", resolved_cmd, e),
            )
        }
    };

    // Update registry.
    let result = with_registry(|reg| {
        if let Some(c) = reg.artifacts.get_mut(id) {
            c.state = ArtifactState::Running;
            c.updated_at = Utc::now();
            c.service = Some(ServiceSpec {
                command: resolved_cmd.clone(),
                port: port_alloc,
                pid: Some(pid),
                env: env.clone(),
            });
            return c.clone();
        }
        cv.clone()
    });
    let updated = match result {
        Ok(c) => c,
        Err(e) => {
            return err(
                "ArtifactServe",
                ErrorKind::ExecutionFailed,
                format!("registry: {}", e),
            )
        }
    };

    ensure_proxy_running(proxy_port);
    ActionResult::ok("ArtifactServe", make_info(&updated, proxy_port), 0)
}

// ── ArtifactSave ───────────────────────────────────────────────────────────────

pub async fn artifact_save(action: &Action, _cfg: &AppConfig) -> ActionResult {
    let Action::ArtifactSave { id, name } = action else {
        return err("ArtifactSave", ErrorKind::Internal, "wrong action variant");
    };
    let outcome = with_registry(|reg| {
        let proxy_port = current_proxy_port(reg);
        let cv = match reg.artifacts.get(id).cloned() {
            Some(c) => c,
            None => return Err(format!("unknown artifact '{}'", id)),
        };
        if cv.persistent {
            return Ok::<_, String>((cv, proxy_port, false));
        }
        let new_root = artifact::saved_dir().join(&cv.id);
        if let Err(e) = std::fs::create_dir_all(artifact::saved_dir()) {
            return Err(format!("mkdir saved/: {}", e));
        }
        // Rename if same FS, copy otherwise.
        if std::fs::rename(&cv.root_path, &new_root).is_err() {
            if let Err(e) = copy_dir_recursive(&cv.root_path, &new_root) {
                return Err(format!("copy to saved: {}", e));
            }
            let _ = std::fs::remove_dir_all(&cv.root_path);
        }
        if let Some(c) = reg.artifacts.get_mut(id) {
            c.persistent = true;
            c.root_path = new_root;
            c.updated_at = Utc::now();
            if let Some(n) = name.clone() {
                c.name = Some(n);
            }
            return Ok((c.clone(), proxy_port, true));
        }
        Err("registry race: artifact vanished mid-save".into())
    });

    match outcome {
        Ok(Ok((cv, port, _migrated))) => ActionResult::ok("ArtifactSave", make_info(&cv, port), 0),
        Ok(Err(m)) => err("ArtifactSave", ErrorKind::InvalidInput, m),
        Err(e) => err(
            "ArtifactSave",
            ErrorKind::ExecutionFailed,
            format!("registry: {}", e),
        ),
    }
}

// ── ArtifactStop ───────────────────────────────────────────────────────────────

pub async fn artifact_stop(action: &Action, _cfg: &AppConfig) -> ActionResult {
    let Action::ArtifactStop { id } = action else {
        return err("ArtifactStop", ErrorKind::Internal, "wrong action variant");
    };
    let pid_opt = match with_registry(|reg| {
        reg.artifacts
            .get(id)
            .and_then(|c| c.service.as_ref())
            .and_then(|s| s.pid)
    }) {
        Ok(p) => p,
        Err(e) => {
            return err(
                "ArtifactStop",
                ErrorKind::ExecutionFailed,
                format!("registry: {}", e),
            )
        }
    };
    if let Some(pid) = pid_opt {
        terminate_pid(pid, 800);
    }
    let _ = with_registry(|reg| {
        if let Some(c) = reg.artifacts.get_mut(id) {
            c.state = ArtifactState::Stopped;
            c.updated_at = Utc::now();
            if let Some(s) = c.service.as_mut() {
                s.pid = None;
            }
        }
    });
    ActionResult::ok(
        "ArtifactStop",
        ActionOutput::ArtifactOpResult {
            id: id.clone(),
            op: "stopped".into(),
            message: "service signalled and reaped".into(),
        },
        0,
    )
}

// ── ArtifactDestroy ────────────────────────────────────────────────────────────

pub async fn artifact_destroy(action: &Action, _cfg: &AppConfig) -> ActionResult {
    let Action::ArtifactDestroy { id, force } = action else {
        return err(
            "ArtifactDestroy",
            ErrorKind::Internal,
            "wrong action variant",
        );
    };
    let force = force.unwrap_or(false);
    let outcome = with_registry(|reg| {
        let cv = match reg.artifacts.get(id).cloned() {
            Some(c) => c,
            None => return Err(format!("unknown artifact '{}'", id)),
        };
        if cv.persistent && !force {
            return Err(format!(
                "artifact '{}' is persistent; pass force=true to destroy",
                id
            ));
        }
        if let Some(s) = &cv.service {
            if let Some(pid) = s.pid {
                if pid_alive(pid) {
                    terminate_pid(pid, 800);
                }
            }
        }
        let _ = std::fs::remove_dir_all(&cv.root_path);
        reg.artifacts.remove(id);
        Ok(cv)
    });
    match outcome {
        Ok(Ok(_)) => ActionResult::ok(
            "ArtifactDestroy",
            ActionOutput::ArtifactOpResult {
                id: id.clone(),
                op: "destroyed".into(),
                message: "files removed and registry cleaned".into(),
            },
            0,
        ),
        Ok(Err(m)) => err("ArtifactDestroy", ErrorKind::InvalidInput, m),
        Err(e) => err(
            "ArtifactDestroy",
            ErrorKind::ExecutionFailed,
            format!("registry: {}", e),
        ),
    }
}

// ── Internal helpers ─────────────────────────────────────────────────────────

fn copy_dir_recursive(src: &std::path::Path, dst: &std::path::Path) -> std::io::Result<()> {
    std::fs::create_dir_all(dst)?;
    for entry in std::fs::read_dir(src)? {
        let entry = entry?;
        let ty = entry.file_type()?;
        let dest = dst.join(entry.file_name());
        if ty.is_dir() {
            copy_dir_recursive(&entry.path(), &dest)?;
        } else if ty.is_file() {
            std::fs::copy(entry.path(), dest)?;
        }
    }
    Ok(())
}

