    #[test]
    fn an_older_sandbox_policy_is_rewritten_once_and_a_custom_one_is_kept() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("x0ne-runtime.toml");
        std::fs::write(
            &path,
            "[runtime]\nmode = \"stdio\"\nprofile = \"sandbox\"\n",
        )
        .unwrap();
        assert!(
            ensure_sandbox_policy_at(&path, "/work").unwrap(),
            "sandbox file without [snapshots] upgraded"
        );
        let upgraded = std::fs::read_to_string(&path).unwrap();
        assert!(upgraded.contains("[snapshots]") && upgraded.contains("/x0ne-snapshots"));
        // The upgrade adds the snapshot store, never policy.
        assert!(!upgraded.contains("[policy]"), "{upgraded}");
        assert!(path.with_extension("toml.bak").exists());
        assert!(
            !ensure_sandbox_policy_at(&path, "/work").unwrap(),
            "current file kept"
        );

        // A file without exec roots is kept narrow, not widened.
        let pre349 = dir.path().join("pre349.toml");
        let mut old = render_sandbox_policy("/work");
        old = old
            .lines()
            .filter(|l| !l.starts_with("allowed_exec_roots"))
            .collect::<Vec<_>>()
            .join("\n");
        std::fs::write(&pre349, &old).unwrap();
        assert!(!ensure_sandbox_policy_at(&pre349, "/work").unwrap());
        assert_eq!(std::fs::read_to_string(&pre349).unwrap(), old);

        let custom = dir.path().join("custom.toml");
        std::fs::write(&custom, "[runtime]\nprofile = \"custom\"\n").unwrap();
        assert!(!ensure_sandbox_policy_at(&custom, "/work").unwrap());
    }

