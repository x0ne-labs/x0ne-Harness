    /// A fresh workspace, in its CANONICAL form, with an `a.txt` in it.
    ///
    /// `/tmp` is a symlink on some machines and the engine compares canonical
    /// paths (`policy.rs:694`). A root written in one form and an action in
    /// the other would never meet, and the cell would measure the test's
    /// plumbing.
    fn canonical_workspace() -> (tempfile::TempDir, String) {
        let dir = tempfile::tempdir().expect("temporary directory");
        let ws = std::fs::canonicalize(dir.path()).expect("the tempdir canonicalizes");
        std::fs::write(ws.join("a.txt"), "x").expect("a.txt");
        let s = ws.display().to_string();
        (dir, s)
    }

    /// Writes the rendered TOML into `dir` and returns the engine built the
    /// way production builds it (`x0ne-runtime/src/main.rs:158`).
    ///
    /// SECURITY: `AppConfig::load` is the ONLY path allowed here. A
    /// `toml::from_str` would not see the merge of `[actions]` with the
    /// compiled defaults (`config.rs:546-551`), and that merge is precisely
    /// what made the three profiles mute for months.
    fn engine_for(
        label: &str,
        dir: &tempfile::TempDir,
        rendered: &str,
    ) -> (
        x0ne_runtime::config::AppConfig,
        x0ne_runtime::policy::PolicyEngine,
    ) {
        let path = dir.path().join("x0ne-runtime.toml");
        std::fs::write(&path, rendered).unwrap();
        let cfg = x0ne_runtime::config::AppConfig::load(&path)
            .unwrap_or_else(|e| panic!("{label}: the runtime must load this policy: {e:#}"));
        let engine = x0ne_runtime::policy::PolicyEngine::new(cfg.clone(), cfg.actions.clone());
        (cfg, engine)
    }

