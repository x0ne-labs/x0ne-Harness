    #[test]
    fn wizard_profiles_render_valid_current_schema_toml() {
        const REQUIRED_POLICY_FIELDS: &[&str] = &[
            "default_effect",
            "max_read_bytes",
            "max_list_entries",
            "allowed_commands",
            "allowed_read_paths",
            "allowed_write_paths",
            "deny_path_patterns",
        ];
        let dirs_str = r#"".", "~""#; // as the wizard renders two picked dirs
        for (name, template) in [
            ("developer", PROFILE_DEVELOPER),
            ("readonly", PROFILE_READONLY),
            ("full", PROFILE_FULL),
            ("sandbox", PROFILE_SANDBOX),
        ] {
            let rendered = render_profile(template, dirs_str);
            let parsed: toml::Table = rendered
                .parse()
                .unwrap_or_else(|e| panic!("{name} profile is not valid TOML: {e}"));
            let policy = parsed
                .get("policy")
                .unwrap_or_else(|| panic!("{name}: no [policy] table"));
            for field in REQUIRED_POLICY_FIELDS {
                assert!(
                    policy.get(field).is_some(),
                    "{name}: [policy] misses required field `{field}` — \
                     the runtime will refuse to boot"
                );
            }
            assert!(
                policy.get("allowed_dirs").is_none(),
                "{name}: `allowed_dirs` is the removed v0.2 key"
            );
            // `confirm` at the RUNTIME level is unsatisfiable: the runtime is
            // driven over stdio and has nobody to ask, so it means "deny every
            // modifying action". The human gate is the orchestrator's. A
            // profile that ships `confirm` here refuses every approved command
            // (field report, 2026-08-12).
            assert_ne!(
                policy.get("mode").and_then(|m| m.as_str()),
                Some("confirm"),
                "{name}: runtime mode `confirm` can never be satisfied — it denies everything"
            );
        }
    }

    /// The sandbox session of 2026-10-06 (`2026-10-05_23-45_902f`, Haiku 4.5):
    /// these exact model outputs were refused as "not in the allowed_commands
    /// list" by the policy run-sandboxed.sh writes, with `cargo` and `ls` in it.
    /// Each goes through the real parse and the real engine.
    #[test]
    fn the_sandbox_policy_runs_a_command_line_the_model_typed_whole() {
        use x0ne_runtime::policy::{DenyReason, PolicyEffect};

        let dir = tempfile::tempdir().expect("temporary directory");
        let (_cfg, engine) = engine_for("sandbox", &dir, &render_sandbox_policy("/work"));
        let parse = |raw: &str| -> x0ne_actions::Action {
            match crate::agent::parse::interpret(raw) {
                crate::agent::parse::TurnInput::Action { action, .. } => {
                    serde_json::from_value(action).expect("a RunCommand")
                }
                other => panic!("{raw}: expected an action, got {other:?}"),
            }
        };

        for raw in [
            r#"<action>{"type":"RunCommand","command":"cargo build --release"}</action>"#,
            r#"<action>{"type":"RunCommand","command":"cargo init /work/mini-nmap --name mini_nmap"}</action>"#,
            r#"<action>{"type":"RunCommand","command":"ls -la /work"}</action>"#,
        ] {
            let effect = engine.evaluate(&parse(raw));
            assert!(
                matches!(effect, PolicyEffect::Allow),
                "{raw}: refused by the sandbox policy: {effect:?}"
            );
        }

        // SECURITY: shell syntax is still not run, and the refusal does not
        // tell the operator to allowlist the whole line. The parser
        // refuses it before the policy (merge of 2026-10-11).
        let raw = r#"<action>{"type":"RunCommand","command":"cd /work/mini-nmap && cargo init --name mini_nmap"}</action>"#;
        match crate::agent::parse::interpret(raw) {
            crate::agent::parse::TurnInput::Action { action, .. } => {
                panic!("{raw}: must stay refused, got the action {action}")
            }
            other => {
                let msg = format!("{other:?}");
                assert!(
                    msg.contains("shell syntax") && msg.contains("args"),
                    "{msg}"
                );
                assert!(!msg.contains("Add `\"cd "), "{msg}");
            }
        }
        // The policy still refuses the whole line if it ever reaches it.
        let whole: x0ne_actions::Action = serde_json::from_value(serde_json::json!(
            {"type": "RunCommand", "command": "cd /work/mini-nmap && cargo init --name mini_nmap"}
        ))
        .expect("a RunCommand");
        assert!(matches!(
            engine.evaluate(&whole),
            PolicyEffect::Deny(DenyReason::CommandNotAllowed { .. })
        ));
    }
