/// The wizard's model step: the provider, then one real call. On a
/// failure it says why and asks; for x0ne-engine too, which startup never
/// asks for and the wizard skipped (2026-10-16).
pub(crate) async fn wizard_connect<F>(
    config: &mut crate::config::Config,
    ask: F,
) -> Result<Box<dyn crate::api::LlmBackend>>
where
    F: for<'c> FnOnce(
        &'c mut crate::config::Config,
    ) -> futures::future::LocalBoxFuture<
        'c,
        Result<Box<dyn crate::api::LlmBackend>>,
    >,
{
    let engine = crate::engine_local::is_engine_provider(&config.llm.provider);
    let failure = match crate::llm_setup::setup_llm(config).await {
        Ok(backend) => match crate::llm_setup::verify_backend(backend.as_ref()).await {
            Ok(()) => return Ok(backend),
            Err(e) => e,
        },
        Err(e) if engine => e,
        Err(e) => return Err(e),
    };
    println!("  {} {:#}", "✗".red(), failure);
    ask(config).await
}

/// The sandbox alternative, shown with every risky choice.
pub const SANDBOX_HINT: &str =
    "Safer: run x0ne inside a sandbox with `make run-incus` (or `make run-podman`); the container is the boundary.";

const HOME_RISK: &str = "Your home directory gives it read and write access to everything in ~: SSH keys, browser profiles, other projects.";
const ROOT_RISK: &str = "The filesystem root gives it read and write access to the whole machine.";

/// The canonical home directory, if there is one.
fn canonical_home() -> Option<PathBuf> {
    dirs::home_dir().map(|h| std::fs::canonicalize(&h).unwrap_or(h))
}

/// Why `dir` is too wide for a project root: `/`, `~`, or a parent of
/// `~`. `None` for an ordinary directory.
pub fn too_wide_root(dir: &str, home: Option<&Path>) -> Option<&'static str> {
    let d = dir.trim();
    if d == "~" || d == "$HOME" || d.is_empty() {
        return Some(HOME_RISK);
    }
    let p = Path::new(d);
    if p.is_absolute() && p.parent().is_none() {
        return Some(ROOT_RISK);
    }
    home.filter(|h| h.starts_with(p)).map(|_| HOME_RISK)
}

/// `picked` as typed in the wizard (`.`, `~`, `~/x`, a path), made absolute
/// against `cwd` at setup time, symlinks resolved when the path exists.
/// A policy root of `.` followed the runtime's launch directory: from `/`, all of it.
pub fn resolve_dirs(picked: &[String], cwd: &Path, home: Option<&Path>) -> Vec<PathBuf> {
    let mut out: Vec<PathBuf> = Vec::new();
    for d in picked {
        let d = d.trim();
        let raw = match (d, home, d.strip_prefix("~/")) {
            ("~" | "$HOME", Some(h), _) => h.to_path_buf(),
            (_, Some(h), Some(rest)) => h.join(rest),
            _ => cwd.join(d),
        };
        let mut lexical = PathBuf::new();
        for c in raw.components() {
            match c {
                std::path::Component::ParentDir => {
                    lexical.pop();
                }
                std::path::Component::CurDir => {}
                other => lexical.push(other),
            }
        }
        let p = std::fs::canonicalize(&lexical).unwrap_or(lexical);
        if !out.contains(&p) {
            out.push(p);
        }
    }
    out
}

/// The host policy for `picked`, resolved against `cwd`, and its roots.
/// A root that is `/`, `~` or a parent of `~` is kept only with
/// `wide_accepted` (the typed yes); with no root left, nothing is written.
pub fn host_policy(
    profile: &str,
    picked: &[String],
    cwd: &Path,
    home: Option<&Path>,
    wide_accepted: bool,
) -> Result<(String, Vec<PathBuf>), String> {
    let all = resolve_dirs(picked, cwd, home);
    let is_wide = |d: &PathBuf| too_wide_root(&d.display().to_string(), home).is_some();
    let dirs: Vec<PathBuf> = all
        .iter()
        .filter(|d| wide_accepted || !is_wide(d))
        .cloned()
        .collect();
    if dirs.is_empty() {
        let wide: Vec<String> = all
            .iter()
            .filter(|d| is_wide(d))
            .map(|d| d.display().to_string())
            .collect();
        return Err(format!(
            "no project directory left: {} is not a project root without a typed yes. \
             Nothing was written; run `x0ne --setup` from the project directory, or give its path.",
            wide.join(", ")
        ));
    }
    let quoted = dirs
        .iter()
        .map(|d| toml::Value::String(d.display().to_string()).to_string())
        .collect::<Vec<_>>()
        .join(", ");
    Ok((render_host_profile(profile, &quoted), dirs))
}

/// The warning for a choice that hands the agent the desktop, all of `~` or
/// the whole machine on the host; `None` when the choice is ordinary.
pub fn risky_choice(profile: &str, dirs: &[String]) -> Option<String> {
    let mut risks = Vec::new();
    if profile == "full" {
        risks.push("Full gives the agent control of your desktop: screenshots, mouse, keyboard, clipboard.");
    }
    let home = canonical_home();
    for d in dirs {
        if let Some(risk) = too_wide_root(d, home.as_deref()) {
            if !risks.contains(&risk) {
                risks.push(risk);
            }
        }
    }
    if risks.is_empty() {
        return None;
    }
    Some(format!(
        "{}\nThis runs on the host, not in a sandbox. {}",
        risks.join("\n"),
        SANDBOX_HINT
    ))
}

/// A risky choice is accepted only by the whole word.
pub fn typed_yes(answer: &str) -> bool {
    let a = answer.trim().to_lowercase();
    a == "yes" || a == "oui"
}

/// Show the warning and read the typed answer.
fn confirm_risk(warning: &str) -> Result<bool> {
    println!();
    for line in warning.lines() {
        println!("  {} {}", "⚠".yellow().bold(), line.yellow());
    }
    print!(
        "  {} ",
        "Type yes (or oui) to accept, anything else to keep it safe:".bold()
    );
    flush();
    Ok(typed_yes(&read_line()?))
}

/// Merge new key=value pairs into an existing .env file without destroying
/// unrelated entries. If the file doesn't exist, creates it.
///
/// `new_content` is a string of `KEY=VALUE\n` lines. For each key:
///   - If it already exists in the file → replace that line
///   - If it's new → append at the end
///   - All other lines (comments, unrelated keys) are preserved
pub fn merge_env_file(path: &str, new_content: &str) {
    // Parse new entries
    let new_entries: Vec<(&str, &str)> = new_content
        .lines()
        .filter(|l| !l.trim().is_empty() && !l.trim_start().starts_with('#'))
        .filter_map(|l| l.split_once('='))
        .collect();

    if new_entries.is_empty() {
        return;
    }

    let existing = std::fs::read_to_string(path).unwrap_or_default();
    let mut result_lines: Vec<String> = Vec::new();
    let mut handled_keys: std::collections::HashSet<&str> = std::collections::HashSet::new();

    // Process existing lines: replace matching keys, keep everything else
    for line in existing.lines() {
        if let Some((key, _)) = line.split_once('=') {
            let key = key.trim();
            // Skip commented-out lines (preserve them as-is)
            if key.starts_with('#') {
                result_lines.push(line.to_string());
                continue;
            }
            if let Some((_, new_val)) = new_entries.iter().find(|(k, _)| k.trim() == key) {
                result_lines.push(format!("{}={}", key, new_val.trim()));
                handled_keys.insert(key);
            } else {
                result_lines.push(line.to_string());
            }
        } else {
            result_lines.push(line.to_string());
        }
    }

    // Append any new keys that weren't already in the file
    for (key, val) in &new_entries {
        let key = key.trim();
        if !handled_keys.contains(key) {
            result_lines.push(format!("{}={}", key, val.trim()));
        }
    }

    // Write back with trailing newline
    let mut output = result_lines.join("\n");
    if !output.ends_with('\n') {
        output.push('\n');
    }
    let _ = std::fs::write(path, output);
    // Security: .env contains API keys — restrict to owner-only
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o600));
    }
}

fn default_config_path() -> PathBuf {
    dirs::config_dir()
        .unwrap_or_else(|| PathBuf::from("~/.config"))
        .join("x0ne")
        .join("x0ne-runtime.toml")
}

/// Does this policy file carry `[runtime] profile = "…"`?
///
/// Read with `toml_edit` and never deserialized: a file that fails to parse
/// answers "no", and the wizard then offers to keep it — which writes the
/// key in place and leaves the rest alone. Refusing to load would be the
/// runtime's job, said at its own startup.
pub fn policy_declares_profile(path: &Path) -> bool {
    let Ok(text) = std::fs::read_to_string(path) else {
        return false;
    };
    let Ok(doc) = text.parse::<toml_edit::DocumentMut>() else {
        return false;
    };
    doc.get("runtime")
        .and_then(|r| r.get("profile"))
        .and_then(|p| p.as_str())
        .is_some_and(|p| !p.is_empty())
}

/// Mark an existing policy as chosen (`profile = "custom"`), in place.
/// `toml_edit`, so every comment and every key survives — the file is the
/// operator's.
fn claim_existing_policy(path: &Path) -> Result<()> {
    let text = std::fs::read_to_string(path)?;
    let mut doc = text
        .parse::<toml_edit::DocumentMut>()
        .with_context(|| format!("invalid TOML in {}", path.display()))?;
    if doc.get("runtime").is_none() {
        doc["runtime"] = toml_edit::table();
    }
    doc["runtime"]["profile"] = toml_edit::value("custom");
    std::fs::write(path, doc.to_string())?;
    Ok(())
}

fn choose_config_path() -> PathBuf {
    // Prefer ~/.config/x0ne/x0ne-runtime.toml
    // Fall back to ./x0ne-runtime.toml if config dir is not writable
    let preferred = default_config_path();
    if let Some(parent) = preferred.parent() {
        if std::fs::create_dir_all(parent).is_ok() {
            return preferred;
        }
    }
    PathBuf::from("x0ne-runtime.toml")
}

