    /// What each profile PROMISES, action by action, tested through the ENGINE.
    ///
    /// The test above reads the `[actions]` map once the file is loaded.
    /// This one submits a REAL action to `PolicyEngine::evaluate`, with an
    /// engine built the way production builds it (`x0ne-runtime/src/main.rs:158`).
    /// The gap is not cosmetic: the map sees neither the desktop gate,
    /// evaluated BEFORE it (`policy.rs:526`), nor the mode (`policy.rs:535-544`),
    /// nor the path and command lists (`policy.rs:673-720`). A profile can
    /// therefore carry `RunCommand = true` and refuse every command it
    /// announces, or declare `[desktop] enabled = false` and suggest, with the
    /// `[actions]` table in hand, that screenshots go through.
    ///
    /// SECURITY: a failure here is the wizard-profiles defect coming back — the three profiles
    /// shipped `RunCommand = false` and `WriteFile = false` on EVERY fresh
    /// install since the start, because their test parsed them instead of
    /// loading them and submitting them to the engine. If a profile no longer
    /// keeps its promise, it is the PROFILE that must be fixed, not this table.
    ///
    /// The tables are literal: nothing is derived from the template, otherwise
    /// the cell would only repeat what the file already says. And each expected
    /// refusal names ITS reason, under a policy where the granted actions of
    /// the same table pass — without that positive control, an engine that
    /// refused everything for any reason would be green.
    /// The verdict as required. The REASON is part of the expectation:
    /// a bare « refused » would be satisfied by any gate located before the
    /// one we think we are measuring.
    #[derive(Debug, PartialEq)]
    enum Verdict {
        Passes,
        ActionSwitchOff,
        DesktopGateOff,
        OutsidePathList(x0ne_runtime::policy::PathAccess),
        CommandNotListed,
    }

    fn verdict(
        engine: &x0ne_runtime::policy::PolicyEngine,
        action: &x0ne_actions::Action,
    ) -> Verdict {
        use x0ne_runtime::policy::{DenyReason, PolicyEffect};
        match engine.evaluate(action) {
            PolicyEffect::Allow => Verdict::Passes,
            PolicyEffect::Deny(DenyReason::ActionDisabled) => Verdict::ActionSwitchOff,
            PolicyEffect::Deny(DenyReason::DesktopDisabled) => Verdict::DesktopGateOff,
            PolicyEffect::Deny(DenyReason::PathNotInAllowlist { access, .. }) => {
                Verdict::OutsidePathList(access)
            }
            PolicyEffect::Deny(DenyReason::CommandNotAllowed { .. }) => Verdict::CommandNotListed,
            // `RequireConfirmation` lands here, on purpose: a profile that went
            // back to `mode = "confirm"` would refuse everything from a
            // runtime nobody can query (field report of 2026-08-12). We want
            // to see it, not tolerate it.
            other => panic!("verdict outside the table: {other:?} for {action:?}"),
        }
    }

