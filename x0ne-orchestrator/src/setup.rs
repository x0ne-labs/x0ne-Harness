/// A sandbox file from before `[snapshots]`, as a document: `profile = "sandbox"` and
/// no `[snapshots]`. Anything else, unreadable files included, is `None`.
fn outdated_sandbox_policy(path: &Path) -> Option<toml_edit::DocumentMut> {
    let doc = std::fs::read_to_string(path)
        .ok()?
        .parse::<toml_edit::DocumentMut>()
        .ok()?;
    let sandbox = doc
        .get("runtime")
        .and_then(|r| r.get("profile"))
        .and_then(|p| p.as_str())
        == Some("sandbox");
    (sandbox && doc.get("snapshots").is_none()).then_some(doc)
}

/// The sandbox policy for one workspace directory.
pub fn render_sandbox_policy(workspace: &str) -> String {
    render_profile(PROFILE_SANDBOX, &format!("{workspace:?}"))
}

/// `DEFAULT_DENY_PATH_PATTERNS` as a TOML array, one pattern per line.
fn default_deny_toml() -> String {
    let lines: String = x0ne_actions::deny_paths::DEFAULT_DENY_PATH_PATTERNS
        .iter()
        .map(|p| format!("  {},\n", toml::Value::String((*p).to_string())))
        .collect();
    format!("[\n{lines}]")
}

/// A template with the shared deny list and its roots (`dirs`, already
/// quoted). The list goes first: a picked directory named `{deny}` stays a path.
fn render_profile(template: &str, dirs: &str) -> String {
    template
        .replace("{deny}", &default_deny_toml())
        .replace("{dirs}", dirs)
}

/// The file the wizard writes for a host profile; unknown names get Developer.
pub fn render_host_profile(profile: &str, dirs: &str) -> String {
    let template = match profile {
        "readonly" => PROFILE_READONLY,
        "full" => PROFILE_FULL,
        _ => PROFILE_DEVELOPER,
    };
    render_profile(template, dirs)
}

/// In a sandbox, the policy is written without a wizard, only where there is
/// none: `true` when the file was written or upgraded.
///
/// SECURITY: an existing file is the operator's policy and is never
/// replaced, profile or not, parseable or not (an unreadable one stops the
/// runtime). A sandbox file from before `[snapshots]` only gains `[snapshots]`; its `[policy]`
/// is left as written, never widened.
pub fn ensure_sandbox_policy_at(path: &Path, workspace: &str) -> Result<bool> {
    if path.exists() {
        let Some(mut doc) = outdated_sandbox_policy(path) else {
            return Ok(false);
        };
        let fresh = render_sandbox_policy(workspace).parse::<toml_edit::DocumentMut>()?;
        if let Some(snapshots) = fresh.get("snapshots") {
            doc.insert("snapshots", snapshots.clone());
        }
        std::fs::copy(path, path.with_extension("toml.bak"))?;
        std::fs::write(path, doc.to_string())?;
        return Ok(true);
    }
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(path, render_sandbox_policy(workspace))?;
    Ok(true)
}

