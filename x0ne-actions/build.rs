//! Generates the action catalog from the `Action` enum at build time.
//!
//! Action identity has to come from one place. Every hand-maintained
//! transcription of it in this workspace had drifted — the snapshot targeting,
//! the confirmation gate, the primitive-collision guard, the model's own
//! prompts — and each drifted silently, because nothing fails when a list stops
//! describing the enum.
//!
//! So the list is not written, it is derived. This parses the enum declaration
//! and emits the variant names, their doc comments, and their field names, so
//! consumers can describe the vocabulary without transcribing it. `all_type_names`
//! previously recovered the same information by parsing a serde error message,
//! which worked but tied discovery to the wording of someone else's diagnostics;
//! that function now reads this table, and a test cross-checks the two so the
//! generator cannot quietly disagree with serde.

use std::path::Path;

fn main() {
    println!("cargo:rerun-if-changed=src/lib.rs");
    let src = std::fs::read_to_string("src/lib.rs").expect("x0ne-actions/src/lib.rs is readable");
    let variants = parse_action_enum(&src);
    let classes = parse_side_effect_classes(&src);
    assert!(
        variants.len() > 50,
        "parsed only {} variants from the Action enum — the parser is out of step \
         with the source, which would silently shrink every derived catalog",
        variants.len()
    );

    let mut out = String::new();
    out.push_str(
        "// @generated by build.rs from src/lib.rs — do not edit.\n\
         /// Build-time description of one `Action` variant.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq)]\n\
         pub struct ActionMeta {\n\
         \x20   /// Wire name, i.e. the value of the `type` field.\n\
         \x20   pub name: &'static str,\n\
         \x20   /// First line of the variant's doc comment, or \"\" if undocumented.\n\
         \x20   pub summary: &'static str,\n\
         \x20   /// Fields that must be present.\n\
         \x20   pub required_fields: &'static [&'static str],\n\
         \x20   /// Fields that may be omitted (serde defaults).\n\
         \x20   pub optional_fields: &'static [&'static str],\n\
         \x20   /// JSON Schema type per field, parallel to required then optional.\n\
         \x20   pub field_types: &'static [(&'static str, &'static str)],\n\
         \x20   /// Side-effect class name, from `side_effect_class`.\n\
         \x20   pub class: &'static str,\n\
         }\n\n\
         /// Every `Action` variant, derived from the enum declaration.\n\
         pub static GENERATED_ACTIONS: &[ActionMeta] = &[\n",
    );
    for v in &variants {
        out.push_str("    ActionMeta {\n");
        out.push_str(&format!("        name: {:?},\n", v.name));
        out.push_str(&format!("        summary: {:?},\n", v.summary));
        out.push_str(&format!(
            "        required_fields: &{:?},\n",
            v.required_fields
        ));
        out.push_str(&format!(
            "        optional_fields: &{:?},\n",
            v.optional_fields
        ));
        out.push_str(&format!("        field_types: &{:?},\n", v.field_types));
        let class = classes
            .get(v.name.as_str())
            .map(|s| s.as_str())
            .unwrap_or("");
        assert!(
            !class.is_empty(),
            "no side_effect_class arm found for {} — the classification is \
             compile-time exhaustive, so this means the parser missed it",
            v.name
        );
        out.push_str(&format!("        class: {:?},\n", class));
        out.push_str("    },\n");
    }
    out.push_str("];\n");

    let dir = std::env::var("OUT_DIR").expect("OUT_DIR set by cargo");
    std::fs::write(Path::new(&dir).join("action_catalog.rs"), out).expect("catalog is writable");
}

struct Variant {
    name: String,
    summary: String,
    required_fields: Vec<String>,
    optional_fields: Vec<String>,
    field_types: Vec<(String, String)>,
}

/// Map each variant to its side-effect class by reading the
/// `side_effect_class` match arms. That function is compile-time exhaustive
/// with no wildcard, so it is a complete and authoritative source — and
/// reading it here means the catalog's notion of "what does this do" cannot
/// disagree with the one every security decision is derived from.
fn parse_side_effect_classes(src: &str) -> std::collections::HashMap<String, String> {
    let mut out = std::collections::HashMap::new();
    let start = match src.find("pub fn side_effect_class(&self)") {
        Some(i) => i,
        None => return out,
    };
    let body = &src[start..];
    let mut pending: Vec<String> = Vec::new();
    for raw in body.lines() {
        let line = raw.trim();
        if line.starts_with("//") {
            continue;
        }
        // Collect `Action::Name { .. }` occurrences on this line.
        let mut rest = line;
        while let Some(i) = rest.find("Action::") {
            let after = &rest[i + "Action::".len()..];
            let end = after
                .find(|c: char| !c.is_alphanumeric() && c != '_')
                .unwrap_or(after.len());
            if end > 0 {
                pending.push(after[..end].to_string());
            }
            rest = &after[end..];
        }
        if let Some(arrow) = line.find("=> S::") {
            let after = &line[arrow + "=> S::".len()..];
            let end = after
                .find(|c: char| !c.is_alphanumeric())
                .unwrap_or(after.len());
            let class = after[..end].to_string();
            for name in pending.drain(..) {
                out.insert(name, class.clone());
            }
        }
        if line == "}" && !out.is_empty() {
            break;
        }
    }
    out
}

/// Rust type → JSON Schema type. Coarse on purpose: the schema exists to tell
/// the model the shape, not to validate on its behalf.
fn json_type_of(rust_type: &str) -> &'static str {
    let t = rust_type.trim();
    let t = t
        .strip_prefix("Option<")
        .and_then(|s| s.strip_suffix('>'))
        .unwrap_or(t)
        .trim();
    if t.starts_with("Vec<") {
        "array"
    } else if t == "String" || t == "&str" {
        "string"
    } else if t == "bool" {
        "boolean"
    } else if t.starts_with('u') || t.starts_with('i') || t.starts_with('f') && t.len() <= 5 {
        "integer"
    } else if t.starts_with("HashMap") || t.starts_with("BTreeMap") {
        "object"
    } else {
        "any"
    }
}

/// Parse the `pub enum Action { … }` declaration.
///
/// Deliberately simple: the enum is plain data with no tuple variants, no
/// variant-level `#[serde(rename)]`, and no multi-line field types. The
/// assertion in `main` catches it if that stops being true, because a parser
/// that silently matches nothing is exactly the failure mode this whole
/// exercise exists to eliminate.
fn parse_action_enum(src: &str) -> Vec<Variant> {
    let start = match src.find("pub enum Action {") {
        Some(i) => i,
        None => return Vec::new(),
    };
    let body = &src[start + "pub enum Action {".len()..];

    let mut variants = Vec::new();
    let mut depth = 0usize;
    let mut pending_doc: Vec<String> = Vec::new();
    let mut pending_serde_default = false;
    let mut current: Option<Variant> = None;

    for raw in body.lines() {
        let line = raw.trim();

        if depth == 0 && line == "}" {
            break; // end of enum
        }

        if let Some(doc) = line.strip_prefix("///") {
            if depth == 0 {
                pending_doc.push(doc.trim().to_string());
            }
            continue;
        }
        if line.starts_with("//") {
            continue;
        }
        if line.starts_with("#[") {
            if line.contains("serde") && line.contains("default") {
                pending_serde_default = true;
            }
            continue;
        }

        if depth == 0 {
            if let Some(name) = variant_name(line) {
                let summary = pending_doc
                    .iter()
                    .find(|l| !l.is_empty())
                    .cloned()
                    .unwrap_or_default();
                pending_doc.clear();
                let v = Variant {
                    name,
                    summary,
                    required_fields: Vec::new(),
                    optional_fields: Vec::new(),
                    field_types: Vec::new(),
                };
                // `Name { … }` on one line, `Name {` opening a block, or `Name,`.
                let opens = line.contains('{') && !line.ends_with("},");
                if line.contains('{') && line.ends_with("},") {
                    // Single-line struct variant: fields are between the braces.
                    let inner = &line[line.find('{').unwrap() + 1..line.rfind('}').unwrap()];
                    let mut v = v;
                    for field in inner.split(',') {
                        if let Some((f, ty)) = field_decl(field.trim()) {
                            v.field_types
                                .push((f.clone(), json_type_of(&ty).to_string()));
                            v.required_fields.push(f);
                        }
                    }
                    variants.push(v);
                } else if opens {
                    current = Some(v);
                    depth = 1;
                } else {
                    variants.push(v);
                }
                pending_serde_default = false;
                continue;
            }
            pending_doc.clear();
            continue;
        }

        // Inside a struct variant.
        if line == "}," || line == "}" {
            if let Some(v) = current.take() {
                variants.push(v);
            }
            depth = 0;
            pending_serde_default = false;
            continue;
        }
        if let Some((f, ty)) = field_decl(line) {
            if let Some(v) = current.as_mut() {
                v.field_types
                    .push((f.clone(), json_type_of(&ty).to_string()));
                if pending_serde_default {
                    v.optional_fields.push(f);
                } else {
                    v.required_fields.push(f);
                }
            }
        }
        pending_serde_default = false;
    }

    variants
}

/// `ReadFile {` / `MoveToTrash { path: String },` / `ListSnapshots,` → the name.
fn variant_name(line: &str) -> Option<String> {
    let end = line.find(|c: char| !c.is_alphanumeric())?;
    let (name, rest) = line.split_at(end);
    if name.is_empty() || !name.starts_with(|c: char| c.is_ascii_uppercase()) {
        return None;
    }
    let rest = rest.trim_start();
    if rest.starts_with('{') || rest == "," {
        Some(name.to_string())
    } else {
        None
    }
}

/// `path: String,` → `("path", "String")`.
fn field_decl(line: &str) -> Option<(String, String)> {
    let colon = line.find(':')?;
    let name = line[..colon].trim();
    if name.is_empty()
        || !name
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
    {
        return None;
    }
    let ty = line[colon + 1..].trim().trim_end_matches(',').trim();
    Some((name.to_string(), ty.to_string()))
}
